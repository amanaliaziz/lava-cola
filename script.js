let current = localStorage.getItem("lang") || "ru";

function setLang(lang) {
  const t = I18N[lang] || I18N.ru;
  current = lang;
  document.documentElement.lang = lang === "kz" ? "kk" : lang;
  document.querySelectorAll("[data-i18n]").forEach(el => {
    const v = t[el.dataset.i18n];
    if (v !== undefined) el.innerHTML = v;
  });
  document.querySelectorAll("[data-i18n-ph]").forEach(el => {
    el.placeholder = t[el.dataset.i18nPh] || "";
  });
  document.querySelectorAll("#lang button").forEach(b =>
    b.classList.toggle("active", b.dataset.lang === lang));
  document.title = t.hero2;
  localStorage.setItem("lang", lang);
}

document.querySelectorAll("#lang button").forEach(b =>
  b.addEventListener("click", () => setLang(b.dataset.lang)));

// Mobile menu
const burger = document.getElementById("burger");
const navLinks = document.getElementById("navLinks");
burger.addEventListener("click", () => navLinks.classList.toggle("open"));
navLinks.querySelectorAll("a").forEach(a =>
  a.addEventListener("click", () => navLinks.classList.remove("open")));

// Animated counters
const counters = document.querySelectorAll("[data-count]");
const io = new IntersectionObserver(entries => {
  entries.forEach(e => {
    if (!e.isIntersecting) return;
    const el = e.target, end = +el.dataset.count, start = performance.now();
    const step = now => {
      const p = Math.min((now - start) / 1200, 1);
      el.textContent = Math.round(end * p);
      if (p < 1) requestAnimationFrame(step);
    };
    requestAnimationFrame(step);
    io.unobserve(el);
  });
}, { threshold: .4 });
counters.forEach(c => io.observe(c));

// Booking form
document.getElementById("bookForm").addEventListener("submit", e => {
  e.preventDefault();
  document.getElementById("formMsg").textContent = I18N[current].thanks;
  e.target.reset();
});

setLang(current);
